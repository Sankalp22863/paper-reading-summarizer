import {test,expect} from '@playwright/test';
import {makePdf} from '../fixtures/pdf.js';
test('goal checklist: pick and add papers, tick off requires PDF and summary',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByLabel('monthly goal progress')).toBeVisible();
 await page.getByRole('button',{name:'Reading goals',exact:true}).click();
 await page.getByRole('button',{name:'Set a goal'}).click();
 await page.getByLabel('Goal name').fill('Near-memory compute');
 await page.getByLabel('New paper title').fill('PIM survey');await page.getByLabel('New paper title').press('Enter');
 await page.getByRole('checkbox',{name:/LoRA/}).check();
 await expect(page.getByLabel('Papers to finish')).toHaveValue('2');
 await page.getByRole('button',{name:'Create goal'}).click();
 const board=page.locator('.goal-board').filter({hasText:'Near-memory compute'});
 await expect(board.locator('.goal-tile')).toHaveCount(2);
 await expect(board).toContainText('0/2');
 await expect(board.locator('.goal-next')).toContainText('PIM survey');
 await board.getByLabel('New paper for Near-memory compute').fill('HBM-PIM');await board.getByRole('button',{name:'Add tile'}).click();
 await expect(board.locator('.goal-tile')).toHaveCount(3);
 await board.getByRole('button',{name:'Complete PIM survey'}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Mark complete'}).click();
 await expect(page.getByRole('alert')).toContainText('annotated PDF');
 await page.getByLabel('Annotated PDF',{exact:true}).setInputFiles({name:'pim.pdf',mimeType:'application/pdf',buffer:makePdf()});
 await expect(page.locator('.pdf-import-status')).not.toContainText('Reading PDF metadata');
 await page.getByRole('dialog').getByRole('button',{name:'Mark complete'}).click();
 await expect(page.getByRole('alert')).toContainText('takeaway');
 await page.locator('#takeaway').fill('Processing in memory cuts data movement.');
 await page.getByRole('dialog').getByRole('button',{name:'Mark complete'}).click();
 await page.getByRole('button',{name:'Close dialog'}).click();
 await expect(board).toContainText('1/3');
 await expect(board.locator('.goal-tile.done')).toHaveCount(1);
 await page.reload();await page.getByRole('button',{name:'Reading goals',exact:true}).click();
 await expect(page.locator('.goal-board').filter({hasText:'Near-memory compute'})).toContainText('1/3');
 expect(errors).toEqual([]);
});
